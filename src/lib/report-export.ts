import type { StartupPlan } from "./startup-generator";

/** Turns a plan into plain text — used by Copy, Print, PDF and DOCX exports. */
export function planToText(plan: StartupPlan): string {
  const L: string[] = [];
  const line = (s = "") => L.push(s);
  const list = (items: string[]) => items.forEach((i) => line(`  • ${i}`));

  line(`${plan.name.toUpperCase()}`);
  line(`${plan.tagline}`);
  line(`Generated on ${new Date(plan.createdAt).toLocaleString()}`);
  line();
  line(
    `Inputs: ${plan.input.domain} | ${plan.input.audience} | ${plan.input.budget} | ${plan.input.country} | ${plan.input.goal} | ${plan.input.technology}`,
  );
  line();
  line("1. STARTUP NAME");
  line(plan.name);
  line();
  line("2. TAGLINE");
  line(plan.tagline);
  line();
  line("3. STARTUP IDEA");
  line(plan.idea);
  line();
  line("4. PROBLEM STATEMENT");
  line(plan.problem);
  line();
  line("5. PROPOSED SOLUTION");
  line(plan.solution);
  line();
  line("6. TARGET CUSTOMERS");
  list(plan.targetCustomers);
  line();
  line("7. BUSINESS MODEL");
  list(plan.businessModel);
  line();
  line("8. REVENUE SOURCES");
  list(plan.revenueSources);
  line();
  line("9. REQUIRED TECHNOLOGIES");
  line(`  Languages: ${plan.technologies.languages.join(", ")}`);
  line(`  Frameworks: ${plan.technologies.frameworks.join(", ")}`);
  line(`  Database: ${plan.technologies.database.join(", ")}`);
  line(`  Cloud: ${plan.technologies.cloud.join(", ")}`);
  line(`  AI Frameworks: ${plan.technologies.aiFrameworks.join(", ")}`);
  line(`  Deployment: ${plan.technologies.deployment.join(", ")}`);
  line();
  line("10. COMPETITOR ANALYSIS");
  plan.competitors.forEach((c) => line(`  • ${c.name} — Strength: ${c.strength}; Weakness: ${c.weakness}`));
  line();
  line("11. SWOT ANALYSIS");
  line(" Strengths:");
  list(plan.swot.strengths);
  line(" Weaknesses:");
  list(plan.swot.weaknesses);
  line(" Opportunities:");
  list(plan.swot.opportunities);
  line(" Threats:");
  list(plan.swot.threats);
  line();
  line("12. MARKETING STRATEGY");
  plan.marketing.forEach((m) => line(`  • ${m.channel}: ${m.plan}`));
  line();
  line("13. ESTIMATED TEAM");
  plan.team.forEach((t) => line(`  • ${t.role} — ${t.responsibility}`));
  line();
  line("14. BUDGET ESTIMATION");
  line(`  Total: ${plan.budget.total}`);
  plan.budget.lines.forEach((b) => line(`  • ${b.label}: ${b.amount} (${b.share}%)`));
  line();
  line("15. DEVELOPMENT ROADMAP");
  plan.roadmap.forEach((r) => line(`  • ${r.month} — ${r.focus}: ${r.deliverables.join(", ")}`));
  line();
  line("16. RISK ANALYSIS");
  plan.risks.forEach((r) => line(`  • ${r.risk} → ${r.mitigation}`));
  line();
  line("17. FUTURE SCOPE");
  list(plan.futureScope);
  line();
  line("18. INVESTOR PITCH");
  line(plan.investorPitch);
  line();
  line("— Generated by AI Startup Idea Generator");
  return L.join("\n");
}

/** Escapes text for safe embedding in exported HTML documents. */
function escapeHtml(value: string) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function planToHtml(plan: StartupPlan) {
  const body = escapeHtml(planToText(plan))
    .split("\n")
    .map((l) => (l.trim() === "" ? "<p>&nbsp;</p>" : `<p>${l.replace(/^ +/, (m) => "&nbsp;".repeat(m.length))}</p>`))
    .join("");
  return `<!doctype html><html><head><meta charset="utf-8"><title>${escapeHtml(plan.name)} — Startup Plan</title>
  <style>body{font-family:Georgia,serif;line-height:1.5;padding:32px;max-width:820px;margin:auto}p{margin:2px 0;white-space:pre-wrap}</style>
  </head><body>${body}</body></html>`;
}

function downloadBlob(content: string, filename: string, type: string) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export function downloadDocx(plan: StartupPlan) {
  downloadBlob(planToHtml(plan), `${plan.name}-startup-plan.docx`, "application/msword");
}

/** Opens the browser print dialog with a clean document (used for PDF + Print). */
export function printPlan(plan: StartupPlan) {
  const win = window.open("", "_blank", "width=900,height=1000");
  if (!win) return;
  win.document.write(planToHtml(plan));
  win.document.close();
  win.focus();
  setTimeout(() => win.print(), 350);
}

export async function copyPlan(plan: StartupPlan) {
  await navigator.clipboard.writeText(planToText(plan));
}

export async function sharePlan(plan: StartupPlan) {
  const text = `${plan.name} — ${plan.tagline}\n\n${plan.investorPitch}`;
  const nav = navigator as Navigator & { share?: (data: ShareData) => Promise<void> };
  if (typeof nav.share === "function") {
    await nav.share({ title: plan.name, text });
    return "shared";
  }
  await nav.clipboard.writeText(text);
  return "copied";
}
